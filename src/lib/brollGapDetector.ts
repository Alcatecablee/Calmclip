import type { TranscriptResult } from './whisper'
import type { SilenceSegment } from './silenceCutter'

export interface Gap {
  start:    number
  end:      number
  duration: number
  noted:    boolean
}

export function detectGaps(
  transcript:  TranscriptResult,
  trimStart:   number,
  trimEnd:     number,
  silenceSegs: SilenceSegment[],
  threshold:   number,
): Gap[] {
  const clipDur = trimEnd - trimStart
  const cuts: { start: number; end: number }[] = []

  for (const s of silenceSegs) {
    cuts.push({ start: s.start, end: s.end })
  }

  const chunks = (transcript.chunks ?? []).filter(c => c.timestamp[0] != null && c.timestamp[1] != null)
  for (let i = 0; i < chunks.length - 1; i++) {
    const gapStart = chunks[i].timestamp[1]!
    const gapEnd   = chunks[i + 1].timestamp[0]!
    if (gapEnd - gapStart >= 3.0) {
      cuts.push({ start: gapStart, end: gapEnd })
    }
  }

  const sortedCuts = cuts.sort((a, b) => a.start - b.start)
  const mergedCuts: { start: number; end: number }[] = []
  for (const c of sortedCuts) {
    const prev = mergedCuts[mergedCuts.length - 1]
    if (prev && c.start <= prev.end + 0.1) {
      prev.end = Math.max(prev.end, c.end)
    } else {
      mergedCuts.push({ ...c })
    }
  }

  const gaps: Gap[] = []
  let lastEnd = 0

  for (const cut of mergedCuts) {
    const cutStart = Math.min(clipDur, Math.max(0, cut.start))
    const cutEnd   = Math.min(clipDur, Math.max(0, cut.end))
    const segmentDuration = cutStart - lastEnd
    if (segmentDuration >= threshold) {
      gaps.push({
        start:    lastEnd,
        end:      cutStart,
        duration: segmentDuration,
        noted:    false,
      })
    }
    lastEnd = Math.max(lastEnd, cutEnd)
  }

  const finalDuration = clipDur - lastEnd
  if (finalDuration >= threshold) {
    gaps.push({
      start:    lastEnd,
      end:      clipDur,
      duration: finalDuration,
      noted:    false,
    })
  }

  return gaps
}

export function exportCueSheet(gaps: Gap[], noted: Set<string>, threshold: number): void {
  function fmt(sec: number): string {
    const m = Math.floor(sec / 60)
    const s = Math.floor(sec % 60)
    return `${m}:${String(s).padStart(2, '0')}`
  }

  const rows: string[] = [
    '"#","Timecode In","Timecode Out","Duration (s)","Status"',
  ]
  gaps.forEach((g, i) => {
    const key    = `${g.start.toFixed(0)}-${g.end.toFixed(0)}`
    const status = noted.has(key) ? 'Noted / Intentional' : 'Needs B-roll'
    rows.push(`"${i + 1}","${fmt(g.start)}","${fmt(g.end)}","${Math.round(g.duration)}","${status}"`)
  })
  rows.push('')
  rows.push(`"Generated by CalmClip, threshold: ${threshold}s"`)
  const csv  = rows.join('\r\n')
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' })
  const url  = URL.createObjectURL(blob)
  const a    = document.createElement('a')
  a.href     = url
  a.download = 'broll-cue-sheet.csv'
  a.click()
  URL.revokeObjectURL(url)
}
